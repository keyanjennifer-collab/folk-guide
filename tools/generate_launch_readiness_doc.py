def header_footer(document: Document) -> None:
    """为每一节添加便于内部流转的页眉和页脚。"""
    for section in document.sections:
        header = section.header.paragraphs[0]
        header.text = "五行五色小程序｜上线前完整功能与实施验收清单"
        header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        footer = section.footer.paragraphs[0]
        footer.text = "内部执行版 V1.0｜状态基准日：2026年8月18日"
        footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for paragraph in (header, footer):
            for run in paragraph.runs:
                run.font.size = Pt(8)
                run.font.color.rgb = RGBColor(132, 143, 136)


def checks(document: Document, items: list[str]) -> None:
    """添加可以在Word中逐项勾选的验收清单。"""
    for item in items:
        paragraph = document.add_paragraph()
        paragraph.paragraph_format.space_after = Pt(4)
        paragraph.add_run("□ ").bold = True
        paragraph.add_run(item)


def status_box(document: Document, title: str, text: str, color: str = "EAF0EB") -> None:
    box = document.add_table(rows=1, cols=1)
    shade(box.cell(0, 0), color)
    paragraph = box.cell(0, 0).paragraphs[0]
    paragraph.add_run(title).bold = True
    paragraph.add_run(text)
    document.add_paragraph()


